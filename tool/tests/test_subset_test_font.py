import importlib.util
from pathlib import Path
import tempfile
import unittest
from unittest import mock

SCRIPT = Path(__file__).resolve().parents[1] / 'subset_test_font.py'
spec = importlib.util.spec_from_file_location('subset_test_font', SCRIPT)
font = importlib.util.module_from_spec(spec)
spec.loader.exec_module(font)


class TestFontSubset(unittest.TestCase):
    def test_charset_is_sorted_deterministic_and_covers_all_sources(self):
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            for name, text in [('dart/packages/a/lib/src/a.dart', '天气'),
                               ('dart/packages/b/test/a.dart', '待办'),
                               ('fixtures/conformance/a/b.json', '澄清')]:
                path = root / name
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding='utf-8')
            chars = font.characters(root)
            self.assertEqual(chars, sorted(set(chars)))
            self.assertEqual(chars, font.characters(root))
            self.assertTrue(set(map(ord, '天气待办澄清')).issubset(chars))
            self.assertTrue(set(range(32, 127)).issubset(chars))

    def test_source_hash_checked_before_network_or_fonttools(self):
        with tempfile.TemporaryDirectory() as directory:
            source = Path(directory) / 'bad.otf'
            source.write_bytes(b'bad font')
            with mock.patch.object(font.urllib.request, 'urlopen') as network:
                with self.assertRaisesRegex(ValueError, 'Source font SHA-256'):
                    font.generate(source, Path(directory) / 'output', [65])
                network.assert_not_called()
            self.assertFalse((Path(directory) / 'output').exists())

    def test_check_lists_missing_codepoints_and_rejects_hash_drift(self):
        import sys
        fake = mock.MagicMock()
        fake.TTFont.return_value.__enter__.return_value.getBestCmap.return_value = {65: 'A'}
        with tempfile.TemporaryDirectory() as directory:
            import json
            output = Path(directory)
            (output / 'ChatWeaveTestSans.otf').write_bytes(b'font')
            manifest = dict(sourceUrl=font.SOURCE_URL, sourceSha256=font.SOURCE_SHA256,
                            outputSha256=font.sha256(b'font'))
            (output / 'manifest.json').write_text(json.dumps(manifest))
            with mock.patch.dict(sys.modules, {'fontTools.ttLib': fake}):
                font.check(output, [65])
                with self.assertRaisesRegex(ValueError, 'U.5929'):
                    font.check(output, [65, ord('天')])
                (output / 'ChatWeaveTestSans.otf').write_bytes(b'tampered')
                with self.assertRaisesRegex(ValueError, 'SHA-256'):
                    font.check(output, [65])

    def test_committed_font_coverage_when_generated(self):
        # Font artifacts are generated by the release/build host. CI always
        # invokes --check unconditionally; local script tests also run pre-generation.
        if not (font.OUTPUT / 'manifest.json').exists():
            self.skipTest('Build host has not generated font artifacts yet')
        if importlib.util.find_spec('fontTools') is None:
            self.skipTest('Actual cmap coverage is enforced by the Dart CI font check')
        font.check(font.OUTPUT, font.characters())

    def test_rendering_principles_are_contiguous_and_unique(self):
        text = (font.ROOT / 'docs/rendering.md').read_text(encoding='utf-8')
        section = text.split('## 1. 原则\n', 1)[1].split('## 2.', 1)[0].strip()
        lines = section.splitlines()
        self.assertEqual(len(lines), 7)
        self.assertTrue(all(line.startswith('- **') for line in lines))
        self.assertEqual(text.count('历史暂停的规范判据是 `step.blockId` 指向中断块'), 1)

    def test_check_cli_wires_current_charset_and_propagates_missing_glyphs(self):
        import contextlib
        import io
        import sys
        with mock.patch.object(sys, 'argv', [str(SCRIPT), '--check']):
            with mock.patch.object(font, 'check') as coverage:
                self.assertEqual(font.main(), 0)
                coverage.assert_called_once_with(font.OUTPUT, font.characters())
            with mock.patch.object(font, 'check', side_effect=ValueError('Missing U+5929')):
                output = io.StringIO()
                with contextlib.redirect_stderr(output):
                    self.assertEqual(font.main(), 1)
                self.assertIn('U+5929', output.getvalue())
